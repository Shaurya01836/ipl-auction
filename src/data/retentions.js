/**
 * Calculate dynamic purse & squad when a user releases or retains players.
 * Every released player refunds their salary to remainingPurse.
 */
export function calculateCustomTeamState(teamId, customRetainedPlayerIds = null) {
  const official = IPL_2027_RETENTIONS[teamId];
  if (!official) return { remainingPurse: 130.0, totalSpent: 0, retainedSquad: [], releasedPlayers: [] };

  if (!customRetainedPlayerIds) {
    return {
      remainingPurse: official.remainingPurse,
      totalSpent: official.totalSpent,
      retentionDeduction: official.retentionDeduction || 0,
      retainedSquad: official.players.map(p => ({
        ...p,
        bid: p.price,
        team: teamId,
        isRetained: true
      })),
      releasedPlayers: []
    };
  }

  const retainedSet = new Set(customRetainedPlayerIds);
  const retainedSquad = [];
  const releasedPlayers = [];
  let totalSpent = 0;

  official.players.forEach(p => {
    if (retainedSet.has(p.id)) {
      retainedSquad.push({
        ...p,
        bid: p.price,
        team: teamId,
        isRetained: true
      });
      totalSpent += p.price;
    } else {
      releasedPlayers.push(p);
    }
  });

  const deduction = official.retentionDeduction || 0;
  const remainingPurse = parseFloat(Math.max(0, TOTAL_SALARY_CAP_CR - totalSpent - deduction).toFixed(2));
  return {
    remainingPurse,
    totalSpent: parseFloat(totalSpent.toFixed(2)),
    retentionDeduction: deduction,
    retainedSquad,
    releasedPlayers
  };
}

/**
 * Builds the player index order for the Mini Auction lot sequence.
 * Includes all modern players without an assigned franchise (!p.team && p.set !== 'Legends'),
 * plus any additional user-released player IDs.
 */
export function getMiniAuctionPoolIndices(userReleasedPlayerIds = []) {
  const userReleasedSet = new Set(userReleasedPlayerIds || []);
  const indices = [];

  IPL_PLAYERS.forEach((p, idx) => {
    if (p.set === 'Legends' && !p.includeInMini) return;
    if (p.excludeFromMini) return;
    if (!p.team || userReleasedSet.has(p.id)) {
      indices.push(idx);
    }
  });

  return indices;
}
